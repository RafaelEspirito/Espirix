-- Espirix v0.4: esquema para PostgreSQL LIMPO. NÃO importa H2 local.
CREATE TABLE empresas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(50) NOT NULL UNIQUE,
    nome VARCHAR(150) NOT NULL
);
CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(200) NOT NULL UNIQUE,
    nome VARCHAR(150) NOT NULL,
    senha_hash VARCHAR(100) NOT NULL,
    perfil VARCHAR(20) NOT NULL,
    empresa_id BIGINT REFERENCES empresas(id),
    ativo BOOLEAN NOT NULL
);
CREATE INDEX ix_usuario_empresa ON usuarios(empresa_id);
CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresas(id),
    razao_social VARCHAR(200) NOT NULL,
    nome_fantasia VARCHAR(200),
    cnpj_cpf VARCHAR(14),
    chave_busca VARCHAR(220) NOT NULL,
    data_cadastro TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_cliente_chave UNIQUE(empresa_id, chave_busca),
    CONSTRAINT uk_cliente_empresa_id UNIQUE(empresa_id, id)
);
CREATE TABLE importacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresas(id),
    nome_arquivo VARCHAR(255) NOT NULL,
    tipo_arquivo VARCHAR(5) NOT NULL,
    data_importacao TIMESTAMP(6) NOT NULL,
    quantidade_registros_novos INTEGER NOT NULL,
    quantidade_atualizados INTEGER NOT NULL,
    quantidade_ignorados INTEGER NOT NULL,
    status VARCHAR(10) NOT NULL,
    mensagem VARCHAR(600),
    sha256 VARCHAR(64)
);
CREATE INDEX ix_importacao_data ON importacoes(data_importacao);
CREATE INDEX ix_importacao_empresa_data ON importacoes(empresa_id, data_importacao DESC);
CREATE TABLE titulos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresas(id),
    numero_nota VARCHAR(100) NOT NULL,
    numero_parcela VARCHAR(30) NOT NULL,
    cliente_id BIGINT NOT NULL,
    tipo_operacao VARCHAR(15) NOT NULL,
    data_emissao DATE NOT NULL,
    data_vencimento DATE NOT NULL,
    data_pagamento DATE,
    valor_original NUMERIC(19,2) NOT NULL,
    valor_pago NUMERIC(19,2) NOT NULL,
    saldo_devedor NUMERIC(19,2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    origem_arquivo VARCHAR(5) NOT NULL,
    versao BIGINT,
    CONSTRAINT fk_titulo_cliente_empresa FOREIGN KEY(empresa_id,cliente_id) REFERENCES clientes(empresa_id,id),
    CONSTRAINT uk_titulo_natural UNIQUE(empresa_id,cliente_id,numero_nota,numero_parcela,tipo_operacao),
    CONSTRAINT uk_titulo_empresa_id UNIQUE(empresa_id,id),
    CONSTRAINT ck_titulo_valores CHECK (valor_original > 0 AND valor_pago >= 0 AND saldo_devedor >= 0 AND valor_pago <= valor_original)
);
CREATE INDEX ix_titulo_vencimento ON titulos(data_vencimento);
CREATE INDEX ix_titulo_empresa_venc ON titulos(empresa_id,data_vencimento);
CREATE TABLE pagamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresas(id),
    titulo_id BIGINT NOT NULL,
    valor NUMERIC(19,2) NOT NULL CHECK(valor > 0),
    usuario_id BIGINT,
    data_pagamento DATE NOT NULL,
    registrado_em TIMESTAMP(6) NOT NULL,
    origem VARCHAR(15) NOT NULL,
    observacao VARCHAR(300),
    importacao_id BIGINT REFERENCES importacoes(id),
    CONSTRAINT fk_pagamento_titulo_empresa FOREIGN KEY(empresa_id,titulo_id) REFERENCES titulos(empresa_id,id)
);
CREATE INDEX ix_pagamento_data ON pagamentos(data_pagamento);
CREATE INDEX ix_pagamento_empresa_data ON pagamentos(empresa_id,data_pagamento);
CREATE TABLE auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresas(id),
    usuario_id BIGINT NOT NULL,
    acao VARCHAR(60) NOT NULL,
    detalhes VARCHAR(600) NOT NULL,
    registrado_em TIMESTAMP(6) NOT NULL
);
CREATE INDEX ix_auditoria_empresa ON auditoria(empresa_id);
